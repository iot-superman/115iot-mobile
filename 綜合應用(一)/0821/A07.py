# 匯入 Raspberry Pi GPIO 控制函式庫
import RPi.GPIO as GPIO

# 匯入 time 函式庫，用來控制延遲時間
import time


# ============================================================
# 繼電器控制腳位
# ============================================================

# 使用 Raspberry Pi 實體 Pin 38
# Pin 38 = BCM GPIO20
relayPin=38


# ============================================================
# GPIO 編號模式
# ============================================================

# 使用 BOARD 模式
# 所以 relayPin=38 代表「實體 Pin 38」
GPIO.setmode(GPIO.BOARD)


# ============================================================
# GPIO 輸出設定
# ============================================================

# 將 Pin 38 設定成輸出模式
GPIO.setup(relayPin, GPIO.OUT)


# ============================================================
# 延遲時間
# ============================================================

# 初始延遲時間設定為 800 ms
# 800 ms = 0.8 秒
dly=800


try:

    # ========================================================
    # 無限循環
    # ========================================================

    while (True):


        # ====================================================
        # Pin 38 輸出 HIGH
        # ====================================================

        GPIO.output(relayPin, True)

        # 在 Terminal 顯示 HIGH
        print("HIGH")


        # ====================================================
        # 延遲
        #
        # dly 的單位是毫秒 ms
        # time.sleep() 使用的單位是秒
        #
        # 所以必須除以 1000
        #
        # 例如：
        # 800 / 1000.0 = 0.8 秒
        # ====================================================

        time.sleep(dly/1000.0)


        # ====================================================
        # Pin 38 輸出 LOW
        # ====================================================

        GPIO.output(relayPin, False)

        # 在 Terminal 顯示 LOW
        print("LOW")


        # ====================================================
        # 再等待相同時間
        # ====================================================

        time.sleep(dly/1000.0)


        # ====================================================
        # 每跑完一次 HIGH → LOW
        # 延遲時間減少 20 ms
        #
        # 例如：
        #
        # 800
        # ↓
        # 780
        # ↓
        # 760
        # ↓
        # 740
        # ...
        #
        # 因此繼電器切換速度會越來越快
        # ====================================================

        dly-=20


        # ====================================================
        # 如果延遲時間小於 100 ms
        # ====================================================

        if (dly<100):

            # 重新回到 800 ms
            # 再重新由慢變快
            dly=800


# ============================================================
# 按 Ctrl + C 停止程式
# ============================================================

except KeyboardInterrupt:

    # 清除 GPIO 設定
    GPIO.cleanup()