import RPi.GPIO as GPIO
import time

# ============================================================
# 使用 Raspberry Pi 實體 Pin 編號
# ============================================================
GPIO.setmode(GPIO.BOARD)


# ============================================================
# 腳位設定
# ============================================================

# PIR 人體紅外線感測器 OUT
# 實體 Pin 11 = GPIO17
pirPin = 11

# 原本 LED1
# 實體 Pin 29 = GPIO5
ledPin1 = 29


# ============================================================
# GPIO 模式設定
# ============================================================

# PIR 是輸入
GPIO.setup(pirPin, GPIO.IN)

# LED 是輸出
GPIO.setup(ledPin1, GPIO.OUT)

# LED 一開始先關閉
# 你的 LED 接法為 Active Low：
# HIGH = 熄滅
# LOW  = 點亮
GPIO.output(ledPin1, True)


try:
    while True:

        # ====================================================
        # 讀取人體紅外線感測器
        # ====================================================
        pirState = GPIO.input(pirPin)


        # ====================================================
        # PIR 偵測到人體
        #
        # 一般 PIR：
        # HIGH = 偵測到人體移動
        # ====================================================
        if pirState == GPIO.HIGH:

            print("偵測到人體 → LED1 點亮")

            # Pin 29 輸出 LOW
            # LED1 點亮
            GPIO.output(ledPin1, False)


        # ====================================================
        # PIR 沒有偵測到人體
        # ====================================================
        else:

            print("沒有偵測到人體 → LED1 熄滅")

            # Pin 29 輸出 HIGH
            # LED1 熄滅
            GPIO.output(ledPin1, True)


        # 每 0.1 秒讀取一次
        time.sleep(0.1)


# ============================================================
# Ctrl + C 停止
# ============================================================
except KeyboardInterrupt:

    print("\n程式停止")


finally:

    # LED 關閉
    GPIO.output(ledPin1, True)

    # 清除 GPIO
    GPIO.cleanup()