public class Main {
    static void main() {
        byte a, b;
        int c;
        int res;
        a = 0b0100_0101;             //  4＊１６　　＋５＝６９；


        b = (byte) 0b1000_1010;      // -128 + 8＊１６　＋１０＝-118；
        /*根據你選中的第 10 行，以下是 `-128` 的繁體中文解釋：
        ## `-128` 的來源

        在 Java 中，`byte` 是有符號 8 位整數，範圍是 `-128` 到 `127`。

        對於 `0b1000_1010`（二進制）：

        **位權重分配**（從右到左，第 0 位到第 7 位）：
        - 第 7 位（最高位）= 1 → 權重為 `-2^7` = **-128**
        - 第 6 位 = 0 → 權重為 `2^6` = 0
        - 第 5 位 = 0 → 權重為 `2^5` = 0
        - 第 4 位 = 0 → 權重為 `2^4` = 0
        - 第 3 位 = 1 → 權重為 `2^3` = 8
        - 第 2 位 = 0 → 權重為 `2^2` = 0
        - 第 1 位 = 1 → 權重為 `2^1` = 2
        - 第 0 位 = 0 → 權重為 `2^0` = 0

        **計算結果**：`-128 + 8 + 2 = -118`

        ## 關鍵點

        `-128` 來自**有符號二進制的最高位**。在補碼表示法中，最高位不是 `+128`，而是 `-128`，這就是負數的來源。
        * */

        c = 0b11111111_11111111_1111111_10001010; // -128 + 8＊１６　＋１０＝-118；
        //  00000000_00000000_0000000_01110101; // 7＊１６　＋５＝１１７；

        System.out.println(a);      // 69
        System.out.println("a<<1 =" + (a << 1)); // 66*2 =138   (0100_1010)
        System.out.println("a<<2 =" + (a << 2));  // 69*4 =276
        System.out.println("a<<2 =" +(byte) (a << 2));  //      (100010100) 16+4+0=20  276-256=20
        // 69*4 =276，但因為 byte 類型的範圍是 -128 到 127，所以結果會被截斷為 -20（276 - 256 = 20，然後再轉換為有符號的 byte 類型）。

        System.out.println("a>>1 =" + (a >> 1)); // 69/2 =34   (0010_0010)
        System.out.println("a>>2 =" + (a >> 2)); // 69/4 =17   (0001_0001)

        System.out.println(a);//69
        System.out.println("a>>>1 =" + (a >>> 1)); // 69/2 =34   (0010_0010) 69 的二進制表示是 0b0100_0101，使用無符號右移（>>>）將其右移一位會得到 0b0010_0010，即 34。
        System.out.println("a>>>2 =" + (a >>> 2)); // 69/4 =17   (0001_0001) 69 的二進制表示是 0b0100_0101，使用無符號右移（>>>）將其右移兩位會得到 0b0001_0001，即 17。




    }
}

