USE CMDEV;
CREATE VIEW CMDEV.EMPDEPT30_VIEW AS
SELECT EMPNO,ENAME, JOB,MANAGER,HIREDATE,SALARY,COMM FROM CMDEV.EMP WHERE DEPTNO=30;

-- 修改
UPDATE CMDEV.EMPDEPT30_VIEW SET COMM=600 WHERE EMPNO=7844;

-- 刪除
DELETE FROM CMDEV.EMPDEPT30_VIEW WHERE EMPNO=9001;

CREATE OR REPLACE VIEW CMDEV.EMPDEPT30_VIEW AS
SELECT EMPNO,ENAME, JOB,MANAGER,HIREDATE,SALARY,COMM FROM CMDEV.EMP WHERE DEPTNO=30 WITH CHECK OPTION;

