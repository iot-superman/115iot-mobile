-- 建立VIEW 注意以下
-- 同一個資料庫，VIEW名稱不可重複，也不可以與資料表名稱相同
-- VIEW 不可與TRIGGER建立連結

-- 使用VIEW
-- 查詢敘述只能使用已存在的VIEW及TABLE
-- 不可使用TEMPORARY資料表
-- 不可以使用使用PROCEDURE，FUNCTION自訂義變數

CREATE VIEW SCALEVIEW AS
SELECT CO.NAME COUNTRY_NAME, CI.NAME CITY_NAME, CO.POPULATION COUNTRY_POP, CI.POPULATION CITY_POP
FROM WORLD.COUNTRY CO, WORLD.CITY CI WHERE CO.CODE=CI.COUNTRYCODE ;

CREATE VIEW NEW_SCALEVIEW
(COUNTRYNAME,CITYNAME,COUNTRY_POP,CITY_POP) AS
SELECT CO.NAME , CI.NAME , CO.POPULATION , CI.POPULATION
FROM WORLD.COUNTRY CO, WORLD.CITY CI WHERE CO.CODE=CI.COUNTRYCODE ;

--  ALTER VIEW 
ALTER VIEW NEW_SCALEVIEW AS SELECT CO.NAME COUNTRY_NAME, CI.NAME CITY_NAME, CO.POPULATION COUNTRY_POP, CI.POPULATION CITY_POP
FROM WORLD.COUNTRY CO, WORLD.CITY CI WHERE CO.CODE=CI.COUNTRYCODE ;
