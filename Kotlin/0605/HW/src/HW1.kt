/*
## 題目 1：計算兩數並使用不同的操作邏輯

設計一個函數：
process(a: Int, b: Int, op: (Int, Int) -> Int)

主程式：
1. 使用 readln() 讀入兩個整數
2. 呼叫二次 process 函式
3. 使用二個 Lambda：
   - 加法
   - 乘法
4. 列印結果
*/

// =====================================================
// process 函式
// 功能：接收兩個整數與 Lambda 運算邏輯
// =====================================================
fun process(
    a: Int,
    b: Int,
    op: (Int, Int) -> Int
): Int {

    // 執行 Lambda 運算
    return op(a, b)
}

fun main() {

    // =====================================================
    // 使用者輸入
    // =====================================================

    print("請輸入第一個整數 a：")
    val a = readln().toInt()

    print("請輸入第二個整數 b：")
    val b = readln().toInt()

    // =====================================================
    // Lambda：加法
    // =====================================================
    val addLambda = { x: Int, y: Int ->
        x + y
    }

    // =====================================================
    // Lambda：乘法
    // =====================================================
    val multiplyLambda = { x: Int, y: Int ->
        x * y
    }

    // =====================================================
    // 呼叫 process 執行加法
    // =====================================================
    val addResult = process(a, b, addLambda)

    // =====================================================
    // 呼叫 process 執行乘法
    // =====================================================
    val multiplyResult = process(a, b, multiplyLambda)

    // =====================================================
    // 顯示結果
    // =====================================================
    println()
    println("===== 計算結果 =====")

    println("a = $a")
    println("b = $b")

    println("a+b=$addResult")
    println("a*b=$multiplyResult")
}