fun gueess10() {

    // =====================================
    // 建立 1~10 範圍
    // =====================================
    var number = 1..10

    // =====================================
    // 隨機數字
    // =====================================
    var v: Int

    // =====================================
    // 次數
    // =====================================
    var no = 1

    // =====================================
    // 使用者猜測值
    // =====================================
    var guess = -1

    // =====================================
    // 隨機產生 1~10 數字
    // =====================================
    v = number.random()

    // =====================================
    // 最多猜 5 次
    // =====================================
    while (guess != v && no < 6) {

        print("第${no++}次，")
        print("請猜一個1到10的數字：")

        // =====================================
        // 讀取輸入
        // =====================================
        guess = readln().toInt()

        // =====================================
        // 判斷大小
        // =====================================
        if (guess < v) {

            println("太小了！")

        } else if (guess > v) {

            println("太大了！")

        } else {

            println("恭喜你猜對了！")
        }
    }
}

