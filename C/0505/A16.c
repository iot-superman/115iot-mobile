#include <stdio.h>
#include <stdlib.h>

/*
 * 主函數 main 採用 (void) 形式，明確指出不接受任何參數。
 */
int main(void) {
  // ==========================================
  // 1. 定義 struct 結構體
  // 定義一個名為 'struct data' 的新資料型別。
  // 它將學生的姓名（字串）和三科成績（整數）整合在一起。
  // ==========================================
  struct data {
    char name[15]; // 姓名成員：一個字元陣列（字串）
    int math;      // 數學分數
    int eng;       // 英文分數
    int chi;       // 國文分數
  };

  // ==========================================
  // 2. 宣告結構體變數與指標
  // 我們建立一個 'struct data' 型別的變數 'student'。
  // 同時，宣告一個名為 'ptr' 的指標，它的型別是「指向 struct data 的指標」。
  // ==========================================
  struct data student;
  struct data *ptr;

  // ==========================================
  // 3. 將指標指向變數 (指標初始化)
  // 關鍵一步：使用取位址運算子 '&' 取得 'student' 變數的記憶體位址，
  // 並將其存入指標 'ptr' 中。現在，'ptr' 指向 'student'。
  // ==========================================
  ptr = &student;

  // ==========================================
  // 4. 核心解說：透過指標獲取使用者輸入
  // 當我們有了指向結構體的指標後，存取其成員有兩種等價語法：
  //   (1) (*ptr).member  (先解引用指標得到物件，再用點運算子)
  //   (2) ptr->member    (C語言專門為此設計的「箭頭運算子」，更簡潔)
  // 這段程式碼統一使用更簡潔的 '->' 語法。
  // ==========================================

  printf("enter name:");
  // gets 是一個不安全的函數（不建議在實際產品中使用，容易造成緩衝區溢位）。
  // 這裡它會讀取使用者輸入的整行字串並存入 ptr->name 所指向的陣列中。
  // (ptr->name 等同於 student.name)
  gets(ptr->name);

  printf("enter Math Score: ");
  // scanf 需要一個記憶體位址來儲存值。
  // &ptr->math 語法表示：
  //   1. 透過指標 'ptr' 找到結構體成員 'math'
  //   2. 再用 '&' 取得該成員的記憶體位址。
  // (這等同於 &student.math)
  scanf("%d", &ptr->math);

  printf("enter English Score: ");
  scanf("%d", &ptr->eng);

  printf("enter Chinese Score: ");
  scanf("%d", &ptr->chi);

  // ==========================================
  // 5. 清除輸入緩衝區 (可選但建議)
  // ==========================================
  fflush(stdin);

  // ==========================================
  // 6. 透過指標印出結果
  // ==========================================
  printf("\nName: %s\n", ptr->name);
  printf("Math Score: %d\n", ptr->math);
  printf("English Score: %d\n", ptr->eng);
  printf("Chinese Score: %d\n", ptr->chi);

  // ==========================================
  // 7. 計算並印出平均分數
  // (ptr->math + ptr->eng + ptr->chi) 的結果是一個整數。
  // 使用 (float) 進行強制型別轉換 (Casting)，將其轉為浮點數，
  // 這樣在除以 3 時才能得到精確的小數點結果。
  // '%.1f' 表示印出浮點數，並保留一位小數。
  // ==========================================
  printf("Average = %.1f\n", (float)(ptr->math + ptr->eng + ptr->chi) / 3);

  // 在 Windows 上暫停程式，以便查看輸出結果
  // 註：在 Linux/macOS 上通常不需要這行，或可改用 getchar();
  system("pause");

  return 0;
}
