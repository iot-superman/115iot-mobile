#include <stdio.h>
#include <stdlib.h>
#include <string.h>
// 計算並印出 a[60] 與 a[50] 的差值
/*
這段程式碼主要是在計算一個數列的 累加和（Prefix Sum） ，並找出特定範圍內的數值總和。

具體邏輯如下：

1. 初始化階段

- 定義了兩個大小為 100 的整數陣列 a 和 b 。
- 使用第一個 for 迴圈將 b[i] 設定為 i （即 b 陣列儲存了 0, 1, 2, ..., 99）。
2. 累加計算階段

- 將 a[0] 設為 0。
- 使用第二個 for 迴圈計算 a[i] = b[i] + a[i-1] 。
- 這代表 a[i] 實際上是在儲存從 0 到 i 的所有整數總和（等差數列級數）。
  - 例如： a[1] = 0 + 1 = 1
  - a[2] = 1 + 2 = 3
  - a[3] = 3 + 3 = 6 ... 以此類推。
3. 輸出結果

- printf("%d", a[60] - a[50]);
- 這行程式碼是在計算從 51 加到 60 的總和。
- 數學原理： (0+1+...+60) - (0+1+...+50) = 51+52+...+60 。
*/
int main(void) {
  int i;
  int a[100];
  int b[100];
  /* 初始化陣列 b，令 b[i] = i */
  for (i = 0; i < 100; i++) {
    b[i] = i;
  }
  /* 計算陣列 a，令 a[i] = b[i] + a[i-1] */
  a[0] = 0;
  for (i = 1; i < 100; i++) {
     a[i] = b[i] + a[i-1];
  }
  /* 印出 a[60] 與 a[50] 的差值 */
  printf("%d\n",a[60]-a[50]);     //1+2+3..+600 - 1+2+3..+50 
 

system("pause");
 
return 0;
}
